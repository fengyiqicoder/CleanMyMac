HEURISTIC_NAME="Stale node_modules"
HEURISTIC_DESCRIPTION="node_modules in projects whose parent directory was modified 90+ days ago."

discover() {
  # Limit search depth to avoid scanning the entire home dir endlessly.
  /usr/bin/find "$HOME" -maxdepth 6 -name node_modules -type d \
    -not -path "*/Library/*" -not -path "*/.Trash/*" \
    -prune 2>/dev/null | while IFS= read -r nm; do
    parent="$(dirname "$nm")"
    days=$(( ( $(date +%s) - $(stat -f '%m' "$parent" 2>/dev/null || echo 0) ) / 86400 ))
    [[ $days -lt 90 ]] && continue
    b=$(path_bytes "$nm")
    [[ "$b" -lt 52428800 ]] && continue  # < 50 MB
    la=$(stat -f '%Sm' -t '%Y-%m-%d' "$parent" 2>/dev/null || echo unknown)
    rec="Safe (90d+ unused, regenerable)"
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "node_modules: $(basename "$parent")" "$nm" "$b" "$la" "$rec" "Re-create with: npm/yarn/pnpm install."
  done
}
